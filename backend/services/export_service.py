def normalize_export_language(output_language: Optional[str]) -> str:
    value = (output_language or "").strip()
    normalized = value.lower().replace("_", "-")
    if normalized in {"zh", "zh-cn", "zh-hans", "chinese", "中文", "简体中文"}:
        return "Chinese"
    if normalized in {"tr", "tr-tr", "turkish", "türkçe", "turkce"}:
        return "Turkish"
    if normalized in {"en", "en-us", "en-gb", "english"}:
        return "English"
    if not value:
        return "Chinese"
    return value if value in EXPORT_LABELS else "English"


_ATX_HEADING_RE = re.compile(r'^(\s{0,3})(#{1,6})(\s+)(.*)$')
_PLACEHOLDER_CHAT_TITLES = {"", "新对话", "new chat", "yeni sohbet"}
_QUESTION_HEADING_MAX = 110


def shift_markdown_headings(text: str, top_level: int) -> str:
    """Re-level the headings of a markdown fragment so its highest heading becomes `top_level`.

    Answers and generated sections bring their own `#`/`##` headings. Placed as-is inside an
    export they land at the same level as (or above) the document's own structure, so the
    outline mixes up. Relative levels inside the fragment are kept; nothing goes past H6.
    """
    lines = text.split('\n')
    in_code = False
    levels = []
    for line in lines:
        if line.strip().startswith('```'):
            in_code = not in_code
            continue
        if not in_code:
            match = _ATX_HEADING_RE.match(line)
            if match:
                levels.append(len(match.group(2)))
    if not levels:
        return text
    offset = top_level - min(levels)
    in_code = False
    out = []
    for line in lines:
        if line.strip().startswith('```'):
            in_code = not in_code
            out.append(line)
            continue
        match = None if in_code else _ATX_HEADING_RE.match(line)
        if match:
            level = min(6, max(1, len(match.group(2)) + offset))
            line = f"{match.group(1)}{'#' * level}{match.group(3)}{match.group(4)}"
        out.append(line)
    return '\n'.join(out)


def question_heading(question: str) -> tuple[str, bool]:
    """A one-line heading for a chat question, and whether the full text must follow it."""
    single_line = re.sub(r'\s+', ' ', question or '').strip()
    single_line = single_line.lstrip('#').strip()
    if len(single_line) <= _QUESTION_HEADING_MAX and '\n' not in (question or '').strip():
        return single_line, False
    cut = single_line[:_QUESTION_HEADING_MAX].rsplit(' ', 1)[0].rstrip(' ,.;:')
    return f"{cut}…", True


class ExportService:

    def __init__(self):
        self._language = "Chinese"
        self._labels: Dict[str, str] = EXPORT_LABELS["Chinese"]
        self._pandoc_available: Optional[bool] = None

    def _configure_language(self, output_language: Optional[str]) -> None:
        self._language = normalize_export_language(output_language)
        self._labels = EXPORT_LABELS.get(self._language, EXPORT_LABELS["English"])

    def _label(self, key: str) -> str:
        return self._labels.get(key, EXPORT_LABELS["English"].get(key, key))

    def _indent_unit(self) -> str:
        # Chinese typography uses full-width first-line indentation; Latin scripts do not.
        return '\u3000\u3000' if self._language == "Chinese" else ''

    def _body_font_name(self) -> str:
        return '宋体' if self._language == "Chinese" else 'Calibri'

    def export_session_to_docx(
        self,
        session_title: str,
        all_messages: List[Dict[str, Any]],
        user_message_ids: Optional[List[str]] = None,
        include_citations: bool = True,
        citation_style: str = "footnote",
        output_language: Optional[str] = None,
    ) -> Tuple[BytesIO, str]:
        from services.citation_history import turn_citation_maps

        self._configure_language(output_language)
        # Each answer is resolved against the citation map of its own turn (see citation_history).
        turn_maps = turn_citation_maps(all_messages)
        for m, turn_map in zip(all_messages, turn_maps):
            m["_turn_citations"] = turn_map
        citations_map: Dict[str, Any] = {}
        for turn_map in turn_maps:
            citations_map.update(turn_map)

        selected_messages = self._select_message_pairs(
            all_messages, user_message_ids
        )

        if not selected_messages:
            raise ValueError(self._label("no_chat_content"))

        questions = [m.get("content") or "" for m in selected_messages if m.get("role") == "user"]
        title = (session_title or "").strip()
        # A single exported answer is titled by its own question: the session title comes
        # from the first question and would mislabel every later one.
        self._question_is_title = len(questions) == 1 and user_message_ids is not None
        if self._question_is_title or title.lower() in _PLACEHOLDER_CHAT_TITLES:
            title = question_heading(questions[0] if questions else "")[0] or self._label("default_chat_title")

        if citation_style == "footnote" and include_citations and citations_map:
            markdown_content = self._generate_chat_markdown_with_footnotes(
                title, selected_messages, citations_map, include_citations
            )
            docx_stream = self._convert_markdown_to_docx(markdown_content)
        else:
            markdown_content = self._generate_chat_markdown(
                title, selected_messages, citations_map, include_citations
            )
            docx_stream = self._convert_markdown_to_docx(markdown_content)

        safe_title = re.sub(r'[\\/:*?"<>|]', '_', title).rstrip(' ._…') or self._label("default_chat_title")
        filename = f"{safe_title}_{datetime.now().strftime('%Y%m%d')}.docx"

        return docx_stream, filename

    def export_workflow_to_docx(
        self,
        workflow_title: str,
        features: List[Dict[str, Any]],
        citations: Optional[Dict[str, Any]] = None,
        include_citations: bool = True,
        citation_style: str = "endnote",
        output_language: Optional[str] = None,
    ) -> Tuple[BytesIO, str]:
        self._configure_language(output_language)

        title = workflow_title or self._label("default_report_title")
        workflow_citations = citations or {}

        references: Dict[int, str] = {}
        used_numbers: set[int] = set()
        for meta in workflow_citations.values():
            if isinstance(meta, dict) and isinstance(meta.get("display_num"), int):
                used_numbers.add(meta["display_num"])
        next_number = 1

        def resolve_citation(local_citations: Dict[str, Any], citation_id: Any) -> str:
            nonlocal next_number
            cid = str(citation_id or "").strip().strip("[]")
            if not cid or not include_citations:
                return ""
            meta = local_citations.get(cid) or workflow_citations.get(cid)
            if not isinstance(meta, dict):
                return ""
            num = meta.get("display_num")
            if not isinstance(num, int):
                while next_number in used_numbers:
                    next_number += 1
                num = next_number
                used_numbers.add(num)
            if num not in references:
                references[num] = self._build_footnote_content(meta)
            return f"[{num}]"

        def block_text(block: Dict[str, Any], local_citations: Dict[str, Any]) -> str:
            chunks: List[str] = []
            for part in (block.get("content_parts") or []):
                if part.get("type") == "text":
                    chunks.append(str(part.get("content") or ""))
                elif part.get("type") == "citation_ref":
                    chunks.append(resolve_citation(local_citations, part.get("citation_id")))
            text = "".join(chunks).strip()
            if not text:
                text = str(block.get("content") or "").strip()
            return text

        md_parts: List[str] = [
            f"# {title}",
            "",
            f"{self._label('exported_at')}{datetime.now().strftime('%Y-%m-%d %H:%M')}",
            "",
            "---",
        ]

        rendered_features = 0
        for feature in features:
            blocks = feature.get("blocks") or []
            status = feature.get("status")
            if not blocks and status not in ("failed", "cancelled"):
                continue

            heading = (feature.get("title") or feature.get("step_name") or "").strip()
            if not heading:
                continue

            md_parts.extend(["", f"## {heading}", ""])
            local_citations = feature.get("citations") or {}

            if not blocks:
                md_parts.append(f"*{self._label('no_section_content')}*")
                rendered_features += 1
                continue

            heading_levels = [
                int(b.get("level") or 3) for b in blocks if b.get("block_type") == "heading"
            ]
            level_offset = 3 - min(heading_levels) if heading_levels else 0
            first_block = blocks[0] if blocks else {}
            skip_first_heading = (
                first_block.get("block_type") == "heading"
                and block_text(first_block, local_citations).strip().lower() == heading.lower()
            )

            for block_index, block in enumerate(blocks):
                block_type = block.get("block_type")
                text = block_text(block, local_citations)

                if block_type == "heading":
                    if block_index == 0 and skip_first_heading:
                        continue
                    level = min(max(int(block.get("level") or 3) + level_offset, 3), 6)
                    if text:
                        md_parts.extend([f"{'#' * level} {text}", ""])
                elif block_type == "list":
                    if text:
                        md_parts.append(f"- {text}")
                elif block_type == "quote":
                    if text:
                        md_parts.extend([f"> {text}", ""])
                elif block_type in ("image", "image_group", "video"):
                    caption = (block.get("caption") or "").strip()
                    if caption:
                        md_parts.extend([
                            f"*{self._label('image_caption').format(caption=caption)}*",
                            "",
                        ])
                else:
                    if not text:
                        continue
                    if (block.get("extra") or {}).get("is_table") and block.get("content"):
                        md_parts.extend(["", str(block["content"]), ""])
                    else:
                        md_parts.extend([text, ""])

            md_parts.append("")
            rendered_features += 1

        if rendered_features == 0:
            raise ValueError(self._label("no_section_content"))

        if include_citations and references:
            md_parts.extend(["", f"## {self._label('references')}", ""])
            for number in sorted(references):
                # A blank line after each entry keeps every reference in its own paragraph.
                md_parts.extend([f"[{number}] {references[number]}", ""])

        markdown_content = "\n".join(md_parts)
        docx_stream = self._convert_markdown_to_docx(markdown_content)

        safe_title = re.sub(r'[\\/:*?"<>|]', '_', title)
        filename = f"{safe_title}_{datetime.now().strftime('%Y%m%d')}.docx"
        return docx_stream, filename

    def _select_message_pairs(
        self,
        all_messages: List[Dict[str, Any]],
        user_message_ids: Optional[List[str]] = None,
    ) -> List[Dict[str, Any]]:
        selected = []
        user_ids_set = set(user_message_ids) if user_message_ids is not None else None

        for i, m in enumerate(all_messages):
            if m['role'] != 'user':
                continue
            if user_ids_set is not None and m['id'] not in user_ids_set:
                continue

            selected.append(m)

            next_user_index = len(all_messages)
            for j in range(i + 1, len(all_messages)):
                if all_messages[j]['role'] == 'user':
                    next_user_index = j
                    break

            last_valid_assistant = None
            for j in range(i + 1, next_user_index):
                next_m = all_messages[j]
                if next_m['role'] == 'assistant' and next_m.get('content'):
                    last_valid_assistant = next_m

            if last_valid_assistant:
                selected.append(last_valid_assistant)
            else:
                selected.pop()  # a question without an answer adds only an empty section

        return selected

    def _generate_chat_markdown_with_footnotes(
        self,
        title: str,
        messages: List[Dict],
        citations_map: Dict[str, Any],
        include_citations: bool,
    ) -> str:
        self._footnotes = []
        self._fn_id_counter = 0
        self._display_num_to_first_fn_id = {}
        self._display_num_to_first_fn_index = {}
        self._fn_index_to_display_num = {}
        self._fn_id_to_export_num = {}
        self._export_num_to_citation = {}
        self._merge_list = []
        self._original_to_export_num = {}
        self._export_num_counter = 0

        md_parts = []
        md_parts.append(f"# {title}\n")
        md_parts.append(f"\n{self._label('exported_at')}{datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
        md_parts.append(f"\n---\n")

        for msg in messages:
            role = msg['role']
            content = msg.get('content', '')

            if role == 'user':
                # Each question is a section (H2); its answer's own headings start at H3.
                heading, needs_full_text = question_heading(content)
                if not getattr(self, "_question_is_title", False):
                    md_parts.append(f"\n## {heading}\n")
                if needs_full_text:
                    quoted = '\n'.join(f"> {line}" if line.strip() else ">" for line in content.strip().split('\n'))
                    md_parts.append(f"{quoted}\n")

            elif role == 'assistant':

                processed = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL)

                turn_map = msg.get('_turn_citations') or citations_map
                if include_citations and turn_map:
                    processed = self._process_chat_citations_for_footnotes(
                        processed, turn_map
                    )
                else:
                    processed = re.sub(r'\[citation_\d+\]', '', processed)

                formatted = self._format_content_for_export(shift_markdown_headings(processed, 2 if getattr(self, '_question_is_title', False) else 3))
                md_parts.append(f"{formatted}\n")
                md_parts.append("\n\n---\n\n")

        if self._footnotes:
            md_parts.append("\n")
            for fn_id, fn_content in self._footnotes:
                fn_content = fn_content.replace('\n', ' ').replace('\r', ' ')
                fn_content = re.sub(r'\s+', ' ', fn_content).strip()
                md_parts.append(f"[^{fn_id}]: {fn_content}\n")

        return '\n'.join(md_parts)

    def _process_chat_citations_for_footnotes(
        self,
        text: str,
        citations_map: Dict[str, Any],
    ) -> str:
        def replace_citation(match):
            citation_key = match.group(0)[1:-1]
            citation = citations_map.get(citation_key)
            if not citation:
                return ''

            if citation.get('display_num') is None:
                return ''

            # Number by source passage, not by the stored display number: older sessions
            # reused display numbers across turns for different passages.
            source_key = citation_identity(citation)
            if source_key not in self._original_to_export_num:
                self._export_num_counter += 1
                self._original_to_export_num[source_key] = self._export_num_counter
            export_num = self._original_to_export_num[source_key]

            self._fn_id_counter += 1
            temp_fn_id = f"fn_{self._fn_id_counter}"
            current_fn_index = len(self._footnotes)
            self._fn_index_to_display_num[current_fn_index] = export_num
            self._fn_id_to_export_num[temp_fn_id] = export_num

            if export_num in self._display_num_to_first_fn_id:
                first_fn_id = self._display_num_to_first_fn_id[export_num]
                first_fn_index = self._display_num_to_first_fn_index[export_num]
                self._merge_list.append((current_fn_index, first_fn_index, export_num))
                merge_marker = self._label("same_citation").format(n=export_num)
                self._footnotes.append((temp_fn_id, merge_marker))
            else:
                self._display_num_to_first_fn_id[export_num] = temp_fn_id
                self._display_num_to_first_fn_index[export_num] = current_fn_index
                fn_content = self._build_footnote_content(citation)
                self._footnotes.append((temp_fn_id, fn_content))

            return f"[^{temp_fn_id}]"

        result = re.sub(r'\[citation_\d+\]', replace_citation, text)
        result = re.sub(r'\]\[\^', '] [^', result)
        return result


    def _generate_chat_markdown(
        self,
        title: str,
        messages: List[Dict],
        citations_map: Dict[str, Any],
        include_citations: bool,
    ) -> str:
        self._footnotes = []
        self._fn_id_counter = 0
        self._display_num_to_first_fn_id = {}
        self._display_num_to_first_fn_index = {}
        self._fn_index_to_display_num = {}
        self._fn_id_to_export_num = {}
        self._export_num_to_citation = {}
        self._merge_list = []
        self._original_to_export_num = {}
        self._export_num_counter = 0

        md_parts = []
        md_parts.append(f"# {title}\n")
        md_parts.append(f"\n{self._label('exported_at')}{datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
        md_parts.append(f"\n---\n")

        for msg in messages:
            role = msg['role']
            content = msg.get('content', '')

            if role == 'user':
                # Each question is a section (H2); its answer's own headings start at H3.
                heading, needs_full_text = question_heading(content)
                if not getattr(self, "_question_is_title", False):
                    md_parts.append(f"\n## {heading}\n")
                if needs_full_text:
                    quoted = '\n'.join(f"> {line}" if line.strip() else ">" for line in content.strip().split('\n'))
                    md_parts.append(f"{quoted}\n")

            elif role == 'assistant':

                processed = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL)

                turn_map = msg.get('_turn_citations') or citations_map
                if include_citations and turn_map:
                    processed = self._replace_citations_inline(processed, turn_map)
                else:
                    processed = re.sub(r'\[citation_\d+\]', '', processed)

                formatted = self._format_content_for_export(shift_markdown_headings(processed, 2 if getattr(self, '_question_is_title', False) else 3))
                md_parts.append(f"{formatted}\n")
                md_parts.append("\n\n---\n\n")

        if include_citations and self._export_num_to_citation:
            md_parts.append(f"\n## {self._label('references')}\n")
            for export_num in sorted(self._export_num_to_citation):
                citation = self._export_num_to_citation[export_num]
                md_parts.append(
                    f"[{export_num}] {self._build_footnote_content(citation)}\n"
                )

        return '\n'.join(md_parts)

    def _replace_citations_inline(
        self, text: str, citations_map: Dict[str, Any]
    ) -> str:
        def replace_fn(match):
            citation_key = match.group(0)[1:-1]
            citation = citations_map.get(citation_key)
            if not citation:
                return ''
            if citation.get('display_num') is None:
                return ''
            source_key = citation_identity(citation)
            if source_key not in self._original_to_export_num:
                self._export_num_counter += 1
                self._original_to_export_num[source_key] = self._export_num_counter
            export_num = self._original_to_export_num[source_key]
            self._export_num_to_citation[export_num] = citation
            return f'[{export_num}]'

        return re.sub(r'\[citation_\d+\]', replace_fn, text)


    def _format_content_for_export(self, content: str) -> str:
        if not content:
            return content

        lines = content.split('\n')
        result_lines = []
        in_code_block = False
        in_table = False
        in_list = False

        def ensure_blank_before():
            if result_lines and result_lines[-1].strip():
                result_lines.append('')

        def is_list_line(s):
            return bool(re.match(r'^[\-\*\+]\s', s) or re.match(r'^\d+\.\s', s))

        for i, line in enumerate(lines):
            stripped = line.strip()

            if stripped.startswith('```'):
                if not in_code_block:
                    ensure_blank_before()
                in_code_block = not in_code_block
                result_lines.append(line)
                continue

            if in_code_block:
                result_lines.append(line)
                continue

            is_table_line = stripped.startswith('|') or '|---|' in stripped or '| --- |' in stripped

            if is_table_line:
                if not in_table:
                    ensure_blank_before()
                    in_table = True
                result_lines.append(line)
                continue
            elif in_table:
                in_table = False
                result_lines.append('')

            is_current_list = is_list_line(stripped)

            if is_current_list:
                if not in_list:
                    ensure_blank_before()
                    in_list = True
                result_lines.append(line)
                continue
            elif in_list:
                in_list = False
                if stripped:
                    result_lines.append('')

            if stripped.startswith('#'):
                ensure_blank_before()
                result_lines.append(line)
                continue

            if stripped.startswith('>'):
                result_lines.append(line)
                continue

            if stripped.startswith('**') and stripped.endswith('**') and len(stripped) < 50:
                ensure_blank_before()
                result_lines.append(line)
                continue

            if not stripped:
                result_lines.append(line)
                continue

            INDENT = self._indent_unit()
            if not INDENT:
                result_lines.append(line)
                continue
            prev_line_empty = (i == 0) or (i > 0 and not lines[i-1].strip())
            if prev_line_empty:
                result_lines.append(INDENT + stripped)
            else:
                result_lines.append(line)

        return '\n'.join(result_lines)

    def _indent_paragraph(self, text: str) -> str:
        if not text:
            return text

        INDENT = self._indent_unit()
        if not INDENT:
            return text

        lines = text.split('\n')
        if lines:
            first_line = lines[0].lstrip()
            if first_line:
                lines[0] = INDENT + first_line

        return '\n'.join(lines)

    def _strip_italic_markers(self, text: str) -> str:
        if not text:
            return text

        pattern = r'(?<!\*)\*([^*]+)\*(?!\*)'
        return re.sub(pattern, r'\1', text)

    def _normalize_markdown_table(self, content: str) -> str:
        lines = content.strip().split('\n')
        if not lines:
            return content

        table_rows = []
        separator_found = False

        for line in lines:
            line = line.strip()
            if not line:
                continue

            if re.match(r'^\|[\s\-:|]+\|$', line):
                separator_found = True
                table_rows.append(line)
                continue

            if '|' in line:
                if not line.startswith('|'):
                    line = '| ' + line
                if not line.endswith('|'):
                    line = line + ' |'
                table_rows.append(line)

        if not table_rows:
            return content

        max_cols = 0
        for row in table_rows:
            if not re.match(r'^\|[\s\-:|]+\|$', row):
                cells = row.split('|')[1:-1]
                max_cols = max(max_cols, len(cells))

        if max_cols == 0:
            return content

        normalized_rows = []
        for row in table_rows:
            if re.match(r'^\|[\s\-:|]+\|$', row):
                normalized_rows.append('| ' + ' | '.join(['---'] * max_cols) + ' |')
            else:
                cells = row.split('|')[1:-1]
                while len(cells) < max_cols:
                    cells.append('')
                cells = cells[:max_cols]
                normalized_rows.append('| ' + ' | '.join(c.strip() for c in cells) + ' |')

        if not separator_found and len(normalized_rows) > 0:
            separator = '| ' + ' | '.join(['---'] * max_cols) + ' |'
            normalized_rows.insert(1, separator)

        return '\n'.join(normalized_rows)

    def _build_footnote_content(self, citation: Dict[str, Any]) -> str:
        citation_type = citation.get('type', 'segment')

        is_web_citation = (
            citation_type == 'web' or
            (citation.get('url') and not citation.get('file_name'))
        )

        if is_web_citation:
            title = citation.get('title') or self._label('unknown_title')
            url = citation.get('url', '')
            source = citation.get('source', '')
            parts = [title]
            if source:
                parts.append(f"{self._label('source')}: {source}")
            if url:
                parts.append(f"[{self._label('view_original')}]({url})")
            return ' | '.join(parts)

        ref = citation.get('_ref')
        if isinstance(ref, dict) and ref.get('name'):
            return self._format_reference(ref)

        file_name = citation.get('file_name', '')
        page = citation.get('page') or citation.get('start_page')
        segment_id = citation.get('segment_id')

        source_parts = []
        if file_name:
            source_parts.append(self._label('file_name').format(name=file_name))
        if page:
            source_parts.append(self._label('page').format(page=page))

        source_str = (
            ' | '.join(source_parts)
            if self._language != "Chinese"
            else ''.join(source_parts)
        ) or self._label('unknown_source')

        content = self._get_citation_content(citation, segment_id)

        if content:
            content = self._truncate_footnote_content(content)
            return f"{source_str}: {content}" if self._language != "Chinese" else f"{source_str}：「{content}」"

        return source_str

    def _format_reference(self, ref: Dict[str, Any]) -> str:
        """Work name, page (when known) and one verbatim sentence to search for in the work."""
        location = ''
        if ref.get('page'):
            if ref.get('volume'):
                location = self._label('volume_page').format(volume=ref['volume'], page=ref['page'])
            elif ref.get('page_kind') == 'pdf':
                location = self._label('pdf_page').format(page=ref['page'])
            else:
                location = self._label('page').format(page=ref['page'])
        sentence = (ref.get('sentence') or '').strip()
        if self._language == "Chinese":
            head = f"《{ref['name']}》{location}"
            return f"{head}：「{sentence}」" if sentence else head
        head = f"{ref['name']}, {location}" if location else ref['name']
        return f"{head} — “{sentence}”" if sentence else head

    def _truncate_footnote_content(self, content: str) -> str:
        if not content:
            return ''

        content = content.strip()
        if len(content) <= MAX_FOOTNOTE_CONTENT_LENGTH:
            return content

        head = content[:FOOTNOTE_HEAD_LENGTH]
        tail = content[-FOOTNOTE_TAIL_LENGTH:]
        ellipsis = "……" if self._language == "Chinese" else "..."
        return f"{head}{ellipsis}{tail}"

    def _is_pandoc_usable(self) -> bool:
        import shutil
        import subprocess

        candidates: List[str] = []
        system_pandoc = shutil.which('pandoc')
        if system_pandoc:
            candidates.append(system_pandoc)

        try:
            import pypandoc
            bundled = os.path.join(os.path.dirname(pypandoc.__file__), 'files', 'pandoc')
            if os.path.exists(bundled):
                candidates.append(bundled)
        except Exception:
            pass

        for candidate in candidates:
            try:
                result = subprocess.run(
                    [candidate, '--version'],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    timeout=10,
                )
                if result.returncode == 0:
                    return True
            except Exception:
                continue
        # Silent degradation made a broken/foreign-architecture pandoc binary look like a
        # formatting choice. Say so in the log: the built-in writer emits endnotes, not
        # real Word footnotes.
        logger.warning(
            "Pandoc is not usable (%s); DOCX export falls back to the built-in writer, "
            "which produces endnotes instead of real Word footnotes.",
            ", ".join(candidates) or "not found",
        )
        return False

    def _convert_markdown_to_docx(self, markdown_content: str) -> BytesIO:
        """Markdown to DOCX, with right-to-left text (e.g. Arabic) marked so Word can draw it."""
        from services.docx_rtl import fix_rtl_text

        stream = self._convert_markdown_to_docx_raw(markdown_content)
        try:
            fixed = BytesIO(fix_rtl_text(stream.getvalue()))
            fixed.seek(0)
            return fixed
        except Exception as exc:
            logger.warning("Could not mark right-to-left text in DOCX (%s: %s)", type(exc).__name__, exc)
            stream.seek(0)
            return stream

    def _convert_markdown_to_docx_raw(self, markdown_content: str) -> BytesIO:
        if self._pandoc_available is None:
            self._pandoc_available = self._is_pandoc_usable()

        if not self._pandoc_available:
            return self._build_docx_from_markdown(markdown_content)

        try:
            stream = self._convert_markdown_to_docx_with_pandoc(markdown_content)
            return stream
        except Exception as exc:
            self._pandoc_available = False
            logger.warning(
                "Pandoc DOCX conversion failed (%s: %s); using built-in DOCX writer",
                type(exc).__name__,
                exc,
            )
            return self._build_docx_from_markdown(markdown_content)

    def _convert_markdown_to_docx_with_pandoc(self, markdown_content: str) -> BytesIO:
        import shutil

        # pypandoc probes its bundled binary even when a usable system pandoc exists. On
        # Apple Silicon the pypandoc-binary wheels (still as of 1.17) ship an x86_64 pandoc
        # that cannot be exec'd and logs a traceback. Point pypandoc at the working system
        # binary first so the unusable one is never tried.
        system_pandoc = shutil.which("pandoc")
        if system_pandoc:
            os.environ.setdefault("PYPANDOC_PANDOC", system_pandoc)
        import pypandoc

        with tempfile.NamedTemporaryFile(mode='w', suffix='.md', delete=False, encoding='utf-8') as md_file:
            md_file.write(markdown_content)
            md_path = md_file.name

        docx_path = md_path.replace('.md', '.docx')

        try:
            # Images are dropped before pandoc writes the DOCX. Otherwise a Markdown image such
            # as ![](/etc/passwd) in a chat answer or session title would make pandoc embed any
            # file the backend can read. Exports never embed images (they become captions).
            extra_args = ['--standalone', '--lua-filter=' + self._no_local_files_filter()]
            if self._has_reference_docx():
                extra_args.append('--reference-doc=' + self._get_reference_docx())

            pypandoc.convert_file(
                md_path,
                'docx',
                outputfile=docx_path,
                extra_args=extra_args
            )

            self._merge_duplicate_footnotes(docx_path)

            self._adjust_footnote_style(docx_path)

            with open(docx_path, 'rb') as f:
                docx_stream = BytesIO(f.read())
            docx_stream.seek(0)

            return docx_stream

        finally:
            if os.path.exists(md_path):
                os.remove(md_path)
            if os.path.exists(docx_path):
                os.remove(docx_path)

